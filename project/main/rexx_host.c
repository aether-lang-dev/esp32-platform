/* A C host for the RexxAE engine on an ESP32-S3 (ESP-IDF app_main), or on a
 * desktop (plain main) for checking the scripts before flashing.
 *
 * It runs two embedded scripts through RexxAE's step API:
 *   demo.rexx  - SAY, a registered host FUNCTION (DOUBLE) round-trip, a DO
 *                loop, and a small instruction budget so RUNNABLE is seen;
 *   bench.rexx - ~100 lines (routines, SELECT, PARSE, string builtins),
 *                parsed and run once with a timer around it.
 * and prints heap/stack figures as "MEASURE key value" lines that the lane
 * script turns into the README table. */
#include "rexxae.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#ifndef CYCLES
#define CYCLES 50
#endif

#ifdef ESP_PLATFORM
#include "esp_heap_caps.h"
#include "esp_timer.h"
#include "esp_system.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
extern const char demo_rexx_start[] asm("_binary_demo_rexx_start");
extern const char bench_rexx_start[] asm("_binary_bench_rexx_start");
static int64_t now_us(void) { return esp_timer_get_time(); }
static void heap(const char *when) {
    printf("MEASURE heap.%s.internal_free %u\n", when,
           (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT));
    printf("MEASURE heap.%s.internal_min %u\n", when,
           (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT));
    printf("MEASURE heap.%s.internal_largest %u\n", when,
           (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT));
    printf("MEASURE heap.%s.psram_free %u\n", when,
           (unsigned)heap_caps_get_free_size(MALLOC_CAP_SPIRAM));
    printf("MEASURE heap.%s.psram_min %u\n", when,
           (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_SPIRAM));
}
static void stack(const char *when) {
    /* High-water mark: the least free stack this task has ever had (bytes). */
    printf("MEASURE stack.%s.main_free_min %u\n", when,
           (unsigned)uxTaskGetStackHighWaterMark(NULL));
}
#else
#include <time.h>
#include "demo_rexx.h"   /* generated by xxd -i for the desktop check */
#include "bench_rexx.h"
static const char *demo_rexx_start, *bench_rexx_start;
static int64_t now_us(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (int64_t)ts.tv_sec * 1000000 + ts.tv_nsec / 1000;
}
static void heap(const char *when) { (void)when; }
static void stack(const char *when) { (void)when; }
#endif

#if defined(ESP_PLATFORM) && defined(AE_TRACE_ALLOC)
/* Diagnostic (lane.sh with AE_TRACE_ALLOC=1): report each allocation of
 * 4 KB or more made from this component, with its caller, to find what
 * lands in PSRAM. Linked with -Wl,--wrap=malloc/calloc/realloc. */
void *__real_malloc(size_t);
void *__real_calloc(size_t, size_t);
void *__real_realloc(void *, size_t);
#define BIG 4096
void *__wrap_malloc(size_t n) {
    if (n >= BIG) printf("ALLOC malloc %u from %p\n", (unsigned)n, __builtin_return_address(0));
    return __real_malloc(n);
}
void *__wrap_calloc(size_t c, size_t n) {
    if (c * n >= BIG) printf("ALLOC calloc %u from %p\n", (unsigned)(c * n), __builtin_return_address(0));
    return __real_calloc(c, n);
}
void *__wrap_realloc(void *p, size_t n) {
    if (n >= BIG) printf("ALLOC realloc %u from %p\n", (unsigned)n, __builtin_return_address(0));
    return __real_realloc(p, n);
}
#endif

/* Run one context to completion. budget is the instruction allowance per
 * step; quiet suppresses SAY output. Returns the exit code, or -1. */
static int run(RexxAE ctx, int budget, int quiet, int *steps, int *runnable) {
    *steps = 0;
    *runnable = 0;
    for (;;) {
        int status = aether_rexxae_step(ctx, budget);
        ++*steps;
        switch (status) {
        case REXXAE_DONE:
            return aether_rexxae_exit_code(ctx);
        case REXXAE_ERROR:
            printf("REXX ERROR line %d: %s\n", (int)aether_rexxae_line(ctx),
                   aether_rexxae_error(ctx));
            return -1;
        case REXXAE_SAY:
            if (!quiet) printf("REXX> %s\n", aether_rexxae_text(ctx));
            break;
        case REXXAE_RUNNABLE:
            ++*runnable;
            break;
        case REXXAE_FUNCTION: {
            const char *fn = aether_rexxae_function(ctx);
            char value[32];
            if (strcmp(fn, "double") == 0 || strcmp(fn, "DOUBLE") == 0) {
                long n = atol(aether_rexxae_argument_text(ctx, 0));
                snprintf(value, sizeof value, "%ld", 2 * n);
                if (!quiet) printf("HOST  DOUBLE(%ld) -> %s\n", n, value);
                aether_rexxae_reply_value(ctx, value, "");
            } else {
                aether_rexxae_reply_value(ctx, "null", "unknown function");
            }
            break;
        }
        case REXXAE_COMMAND:
            aether_rexxae_reply(ctx, 0, "", "");
            break;
        default:
            printf("unexpected status %d\n", status);
            return -1;
        }
    }
}

static int rexx_main(void) {
    int steps, runnable, rc, ok = 1;

    heap("before_create");
    stack("before_create");
    int64_t t0 = now_us();
    RexxAE ctx = aether_rexxae_create(demo_rexx_start);
    int64_t t1 = now_us();
    if (!ctx) { printf("aether_rexxae_create returned NULL\n"); return 1; }
    if (aether_rexxae_register_function(ctx, "DOUBLE", 1, 1) != 0) {
        printf("register_function failed\n");
        ok = 0;
    }
    heap("after_create");
    printf("MEASURE time.demo_create_us %lld\n", (long long)(t1 - t0));

    /* A budget of 4 instructions per step: the DO loop alone runs ~30. */
    rc = run(ctx, 4, 0, &steps, &runnable);
    printf("demo: exit %d after %d steps, %d RUNNABLE yields\n", rc, steps, runnable);
    if (rc != 0 || runnable == 0) ok = 0;
    heap("after_demo");
    stack("after_demo");
    aether_rexxae_destroy(ctx);
    heap("after_destroy");

    /* The ~100-line benchmark: parse (create) + run, budget 1000 per step. */
    t0 = now_us();
    ctx = aether_rexxae_create(bench_rexx_start);
    t1 = now_us();
    if (!ctx) { printf("bench create failed\n"); return 1; }
    aether_rexxae_register_function(ctx, "DOUBLE", 1, 1);
    rc = run(ctx, 1000, 0, &steps, &runnable);
    int64_t t2 = now_us();
    printf("bench: exit %d after %d steps\n", rc, steps);
    printf("MEASURE time.bench_parse_us %lld\n", (long long)(t1 - t0));
    printf("MEASURE time.bench_run_us %lld\n", (long long)(t2 - t1));
    if (rc != 0) ok = 0;
    heap("after_bench");
    stack("after_bench");
    aether_rexxae_destroy(ctx);
    heap("end");

    /* Retention: what each further create/run/destroy cycle keeps. A runner
     * firmware runs scripts for ever, so anything here accumulates. */
    for (int cycle = 1; cycle <= CYCLES; ++cycle) {
        ctx = aether_rexxae_create(demo_rexx_start);
        if (!ctx) { ok = 0; break; }
        aether_rexxae_register_function(ctx, "DOUBLE", 1, 1);
        if (run(ctx, 1000, 1, &steps, &runnable) != 0) ok = 0;
        aether_rexxae_destroy(ctx);
        if (cycle == 1 || cycle == CYCLES) {
            char when[32];
            snprintf(when, sizeof when, "cycle%d", cycle);
            heap(when);
        }
    }
    printf("MEASURE cycles %d\n", CYCLES);

    /* The same with a distinct source text each cycle, to tell a per-source
     * cache from a one-off warm-up. */
    for (int cycle = 1; cycle <= CYCLES; ++cycle) {
        char src[160];
        snprintf(src, sizeof src,
                 "n = %d\nDO i = 1 TO 3\n  n = n + i\nEND\nIF n > 0 THEN x = 'ok%d'\nEXIT 0\n",
                 cycle, cycle);
        ctx = aether_rexxae_create(src);
        if (!ctx) { ok = 0; break; }
        if (run(ctx, 1000, 1, &steps, &runnable) != 0) ok = 0;
        aether_rexxae_destroy(ctx);
        if (cycle == 1 || cycle == CYCLES) {
            char when[32];
            snprintf(when, sizeof when, "unique%d", cycle);
            heap(when);
        }
    }

    printf(ok ? "REXXAE LANE OK\n" : "REXXAE LANE FAILED\n");
    return ok ? 0 : 1;
}

#ifdef ESP_PLATFORM
void app_main(void) { rexx_main(); }
#else
int main(void) {
    static char demo[sizeof demo_rexx + 1], bench[sizeof bench_rexx + 1];
    memcpy(demo, demo_rexx, sizeof demo_rexx);
    memcpy(bench, bench_rexx, sizeof bench_rexx);
    demo_rexx_start = demo;
    bench_rexx_start = bench;
    return rexx_main();
}
#endif
